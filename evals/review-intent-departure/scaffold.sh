cat > intent.md <<'MD'
# Intent: Donor return

## Problem

Most people who give to the food bank for the first time never give again. About 12% of
first-time donors make a second donation within a year.

## Why it matters

Repeat donors cost far less to keep than new donors cost to find, and they fund most of the
winter programme.

## Success

At least 25% of first-time donors make a second donation within 12 months.

## Constraints

No budget for paid tools this year.

## Out of scope

Attracting new donors.

## Open questions

None.
MD
