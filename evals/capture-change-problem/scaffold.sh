# Intent: Saturday shift cover

## Problem

About a third of Saturday shifts at the food bank are short-staffed, because volunteers forget
or drop out without notice. The coordinator spends Friday evenings phoning around to fill gaps.

## Why it matters

Short shifts mean fewer families served on the busiest day, and the coordinator is burning out.

## Success

Saturday shifts are fully staffed at least 90% of the time. The coordinator's Friday calls take
under 30 minutes.

## Constraints

No budget for paid software this year.

## Out of scope

Recruiting new volunteers.

## Open questions

None.
MD
