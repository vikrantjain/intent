# Events committee minutes, 15 September 2026

## Next year's events

The venue budget for 2027 has been cut by half. We can run three of our six regular events, not
all six. We will decide which three at the October meeting on 20 October.

Attendance alone does not settle it. The dinner and the quiz sell out but draw the same small
group, while the walk and the picnic draw different members each year.

Agreed: survey all members before the October meeting. Ask them to rate each of the six events
from 1 to 5, so the ratings rank the events. The 1-to-5 scale matches the 2024 survey, so the
results can be compared. The survey goes out by the end of September, to leave members two weeks
to answer.
MD
